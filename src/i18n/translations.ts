const DICTIONARIES: Record<AppLocale, Record<TranslationKeys, string>> = {
  en,
  'zh-TW': zhTW,
};

export function getTranslations(locale: AppLocale | undefined): Record<TranslationKeys, string> {
  return DICTIONARIES[locale ?? 'en'] ?? en;
}

export function useT(): Record<TranslationKeys, string> {
  const locale = useSettingsStore((s) => s.settings.locale);
  return getTranslations(locale);
}
